// Helper to search locations across India
export function queryLocations(query: string, limit = 25): AdministrativeUnit[] {
  if (!query || query.trim().length === 0) return [];
  const q = query.trim().toLowerCase();

  return MASTER_LOCATIONS.filter((loc) => {
    if (loc.normalizedName.includes(q) || loc.name.toLowerCase().includes(q)) return true;
    if (loc.district.toLowerCase().includes(q)) return true;
    if (loc.subDistrict.toLowerCase().includes(q)) return true;
    if (loc.state.toLowerCase().includes(q)) return true;
    if (loc.pincode && loc.pincode.startsWith(q)) return true;
    if (loc.aliases.some((a) => a.toLowerCase().includes(q))) return true;
    return false;
  }).slice(0, limit);
}

// Helper to find closest location by spatial coordinate
export function findClosestUnit(lat: number, lng: number): AdministrativeUnit {
  let closest = MASTER_LOCATIONS[0];
  let minD = Infinity;

  for (const loc of MASTER_LOCATIONS) {
    const dLat = loc.latitude - lat;
    const dLng = loc.longitude - lng;
    const distSq = dLat * dLat + dLng * dLng;
    if (distSq < minD) {
      minD = distSq;
      closest = loc;
    }
  }

  return closest;
}
