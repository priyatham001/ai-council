export interface AdministrativeUnit {
  id: string;
  name: string;
  normalizedName: string;
  type: 'village' | 'town' | 'city' | 'taluka' | 'mandal' | 'tehsil';
  country: 'India';
  state: string;
  district: string;
  subDistrict: string; // Mandal for AP/TS, Taluka for MH, Tehsil for others
  subDistrictType: 'Taluka' | 'Mandal' | 'Tehsil' | 'Sub-District';
  latitude: number;
  longitude: number;
  pincode?: string;
  aliases: string[];
  source: 'csv' | 'database';
  popular?: boolean;
}

export function getSubDistrictLabel(state: string): 'Taluka' | 'Mandal' | 'Tehsil' | 'Sub-District' {
  const s = (state || '').toLowerCase();
  if (s.includes('maharashtra') || s.includes('karnataka') || s.includes('gujarat') || s.includes('goa')) {
    return 'Taluka';
  }
  if (s.includes('andhra') || s.includes('telangana')) {
    return 'Mandal';
  }
  if (
    s.includes('uttar pradesh') ||
    s.includes('madhya pradesh') ||
    s.includes('rajasthan') ||
    s.includes('punjab') ||
    s.includes('haryana') ||
    s.includes('bihar') ||
    s.includes('himachal') ||
    s.includes('uttarakhand')
  ) {
    return 'Tehsil';
  }
  return 'Sub-District';
}

