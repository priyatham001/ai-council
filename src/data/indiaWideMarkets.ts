// Great-circle Haversine distance in KM
export function haversineKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

// Estimates road distance factoring actual winding index (~1.22x)
export function calculateRoadDistance(straightDist: number): number {
  if (straightDist <= 3) return Math.max(1, straightDist);
  if (straightDist <= 15) return Math.round(straightDist * 1.16);
  return Math.round(straightDist * 1.22);
}

// Discovers geographically relevant markets with progressive search radius
export function findGeographicMarkets(
  farmerLat: number,
  farmerLng: number,
  cropModalPrice: number = 2320,
  farmerState?: string,
  maxRadiusKm = 350
): MarketItem[] {
  const withDistance = INDIA_WIDE_MARKET_DATABASE.map((m) => {
    const straightDist = haversineKm(farmerLat, farmerLng, m.latitude, m.longitude);
    const roadDist = calculateRoadDistance(straightDist);
    const travelTimeHours = Math.round((roadDist / 38) * 10) / 10;

    // Determine state price variance
    const isSameState = m.state.toLowerCase() === (farmerState || '').toLowerCase();
    const baseVariance = (m.pricePerQuintal % 120) - 40;
    const proximityAdjustedPrice = Math.max(
      100,
      cropModalPrice + baseVariance + (isSameState ? 0 : 25)
    );

    return {
      ...m,
      distanceKm: straightDist,
      roadDistanceKm: roadDist,
      travelTimeHours,
      pricePerQuintal: proximityAdjustedPrice,
    };
  });

  // Sort by road distance (closest first)
  withDistance.sort((a, b) => a.distanceKm - b.distanceKm);

  // Progressive radius checking: 25 -> 50 -> 100 -> 150 -> 250 -> 350 km
  const RADII = [25, 50, 100, 150, 250, maxRadiusKm];
  for (const r of RADII) {
    const candidates = withDistance.filter((m) => m.distanceKm <= r);
    if (candidates.length >= 3) {
      return candidates.slice(0, 6);
    }
  }

  // Fallback: return the 4 closest accessible markets
  return withDistance.slice(0, 4);
}
